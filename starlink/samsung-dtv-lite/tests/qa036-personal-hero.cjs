'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(__dirname+'/../app/discovery.js','utf8'),ctx);
const m=ctx.module.exports;

const rioSD=m.normalize('live',{name:'Globo RJ SD',stream_id:10,stream_icon:'https://img.test/globo.png'},'Abertos');
const rioHD=m.normalize('live',{name:'Globo RJ HD',stream_id:11,stream_icon:'https://img.test/globo.png'},'Abertos');
const series=m.normalize('series',{name:'Inferno Sobre Rodas',series_id:90,cover:'https://img.test/inferno.jpg'},'Drama');
const film=m.normalize('movie',{name:'O Último Aventureiro',stream_id:52,stream_icon:'https://img.test/film.jpg'},'Aventura');
const channelGroup=m.groupLive([rioSD,rioHD])[0];
const items=[channelGroup,series,film];
let viewing={};
assert.equal(m.personalHero(items,viewing,[]),null,'new account must not claim viewing history');
viewing=m.recordViewing(viewing,rioSD,60000,100000);
viewing=m.recordViewing(viewing,rioHD,40000,110000);
let hero=m.personalHero(items,viewing,[]);
assert.equal(hero.item.key,channelGroup.key,'SD+HD time must count toward one channel');
assert.equal(hero.reason,'watched');
assert.equal(hero.watchMs,100000);
assert.equal(hero.item.title,'Globo RJ');
const episode=m.normalizeEpisode({id:881,title:'Episódio 1',season:1,episode_num:1,container_extension:'ts'},series);
viewing=m.recordViewing(viewing,episode,60000,120000);
viewing=m.recordViewing(viewing,episode,60000,125000);
hero=m.personalHero(items,viewing,[]);
assert.equal(hero.item.key,'series:90','episode viewing promotes series artwork');
assert.equal(hero.item.image,'https://img.test/inferno.jpg');
for(let i=0;i<4;i++)viewing=m.recordViewing(viewing,film,60000,130000+i*1000);
assert.equal(m.personalHero(items,viewing,[]).item.key,'movie:52','most watched movie becomes background');
assert.equal(m.personalHero(items,{},['aventura']).item.key,'movie:52','interests are useful with no history');
assert.equal(m.personalHero(items,{},[]),null,'no interest and no history uses brand background');
const before=m.safeViewingStats(viewing);
assert.equal(m.recordViewing(before,rioHD,0,140000)['live:11'].ms,40000,'zero progress is ignored');
assert.equal(m.recordViewing(before,rioHD,300000,140000)['live:11'].ms,100000,'single event delta is capped');
assert.equal(m.recordViewing(before,{key:'live:malicious'},10000,140000)['live:malicious'],undefined,'invalid IDs not persisted');
assert.equal(m.personalHero(items,{'live:10':{ms:30000,lastAt:999999}},[]).reason,'watched');
assert.equal(m.personalHero(items,{'live:10':{ms:30000,lastAt:999999}},[]).item.title,'Globo RJ');
assert.equal(Object.keys(m.safeViewingStats(Object.fromEntries(Array.from({length:250},(_,i)=>['live:'+i,{ms:10000,lastAt:i}])))).length<=80,true,'bounded local usage');
console.log('QA036 personalized hero by viewing time: PASS');
