'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(__dirname+'/../app/discovery.js','utf8'),ctx);
const model=ctx.module.exports;
const channel=model.normalize('live',{name:'TV Brasil',stream_id:730,stream_icon:'https://img.test/bras.png',category_id:'ab',container_extension:'m3u8'},'Canais abertos');
const film=model.normalize('movie',{name:'Aventura Nacional',stream_id:52,stream_icon:'https://img.test/film.jpg',category_id:'film',container_extension:'mp4'},'Aventura');
const series=model.normalize('series',{name:'Série de Aventura',series_id:90,cover:'https://img.test/series.jpg',category_id:'s1'},'Aventura');
assert.equal(channel.kind,'live');assert.equal(channel.key,'live:730');
assert.equal(film.kind,'movie');assert.equal(film.extension,'mp4');
assert.equal(series.key,'series:90');
assert.equal(model.normalize('movie',{stream_id:'not-an-id',name:'Invalid'},'Filmes'),null);
assert.equal(model.playbackUrl('https://panel.test','user','pw',channel),'https://panel.test/live/user/pw/730.m3u8');
assert.equal(model.playbackUrl('https://panel.test','user','pw',film),'https://panel.test/movie/user/pw/52.mp4');
const episode=model.normalizeEpisode({id:881,title:'Episódio 1',container_extension:'ts',episode_num:1,season:2},series);
assert.equal(model.playbackUrl('https://panel.test','user','pw',episode),'https://panel.test/series/user/pw/881.ts');
assert.equal(episode.seriesKey,'series:90');
assert.throws(()=>model.playbackUrl('http://unsafe','u','p',film),/origin/i);
const list=[channel,film,series];
const mix=model.recommend(list,['aventura'],{},10);
assert.equal(mix.length,3);
assert.equal(mix[0].kind==='movie'||mix[0].kind==='series',true);
assert.equal(model.continueItems(list,{'movie:52':{positionMs:12000,durationMs:90000,updatedAt:2000},'live:730':{positionMs:900,durationMs:0,updatedAt:3000}})[0].key,'movie:52');
const h=model.rememberProgress({},film,20000,90000,5000);
assert.equal(h['movie:52'].positionMs,20000);
assert.equal(model.resumePosition(h,film),20000);
assert.equal(model.resumePosition(h,channel),0);
const completed=model.rememberProgress(h,film,88000,90000,6000);
assert.equal(model.resumePosition(completed,film),0);
const grouped=model.shelves(list,{history:h,interests:['aventura']});
assert.equal(grouped[0].title,'Continuar assistindo');
assert(grouped.some(x=>x.key==='live'));
assert(grouped.some(x=>x.key==='movie'));
assert(grouped.some(x=>x.key==='series'));
const episodes=model.episodesFromDetail({episodes:{'2':[{id:881,title:'Capítulo 1',episode_num:1,season:2},{id:882,title:'Capítulo 2',episode_num:2,season:2}]}},series);
assert.equal(episodes.length,2);
assert.equal(episodes[0].key,'episode:881');
assert.equal(model.nextEpisode(episodes,episodes[0]).key,'episode:882');
assert.equal(model.nextEpisode(episodes,episodes[1]),null);
const eHistory=model.rememberProgress({},episode,16000,80000,7000);
assert.equal(model.resumePosition(eHistory,episode),16000);
const resumed=model.shelves([series,episode],{history:eHistory,interests:[]});
assert.equal(resumed[0].key,'continue');
assert.equal(resumed[0].items[0].key,'episode:881');
console.log('QA036 discovery and playback model: PASS');
