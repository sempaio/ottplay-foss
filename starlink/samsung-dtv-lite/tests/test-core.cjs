const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(__dirname+'/../app/core.js','utf8'),ctx);
const core=ctx.module.exports;
assert.equal(core.isValidAccount({user_info:{auth:1,status:'Active'}}),true);
assert.equal(core.isValidAccount({user_info:{auth:0,status:'Active'}}),false);
assert.equal(core.streamUrl('https://panel.example','usuario','senha',{stream_id:42,container_extension:'m3u8'}),'https://panel.example/live/usuario/senha/42.m3u8');
assert.throws(()=>core.streamUrl('javascript:alert(1)','x','y',{stream_id:42}),/origin/i);
assert.throws(()=>core.streamUrl('https://panel.example','x','y',{stream_id:'abc'}),/stream/i);
assert.equal(core.pickTestChannel([{name:'Outro',stream_id:1},{name:'TV Cultura (720p)',stream_id:9}]).stream_id,9);
assert.equal(core.isTransientLoginFailure('Tempo esgotado'),true);
assert.equal(core.isTransientLoginFailure('Falha de rede'),true);
assert.equal(core.isTransientLoginFailure('HTTP 503'),true);
assert.equal(core.isTransientLoginFailure('HTTP 401'),false);
assert.equal(core.isTransientLoginFailure('Resposta incompatível'),false);
// Login focus navigation: cover the exact regression reported on QA 1.0.0 TV.
assert.equal(core.loginFocusTarget('',13),'username','Enter from unselected page must restore username focus');
assert.equal(core.loginFocusTarget('username',40),'password','Down moves from username to password');
assert.equal(core.loginFocusTarget('password',38),'username','Up moves back to username');
assert.equal(core.loginFocusTarget('username',39),'username-keyboard','Right opens focus path to remote keyboard button');
assert.equal(core.loginFocusTarget('username-keyboard',37),'username','Left returns to text input');
assert.equal(core.loginFocusTarget('password',39),'password-keyboard','Right reaches password remote keyboard');
assert.equal(core.loginFocusTarget('password-keyboard',40),'remember-login','Down from keyboard reaches next form control');
assert.equal(core.loginFocusTarget('password',65376),'login-button','IME Done from password moves to Connect');
assert.equal(core.loginFocusTarget('username',65376),'password','IME Done from username moves to password');
assert.equal(core.loginFocusTarget('login-button',38),'remember-login','Up from Connect returns toward fields');
assert.equal(core.loginFocusTarget('username',38),'username','Top of list never disappears');
assert.equal(core.loginFocusTarget('login-button',40),'login-button','Bottom of list never disappears');
assert.equal(core.loginFocusTarget('password',13),'','Enter on an input remains available for native IME');
assert.equal(core.loginFocusTarget('username',10009),'','Back remains the Samsung system key');
